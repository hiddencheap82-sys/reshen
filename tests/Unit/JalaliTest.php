    #[DataProvider('dates')]
    public function test_gregorian_to_jalali(string $gregorian, int $jy, int $jm, int $jd): void
    {
        $d = new DateTimeImmutable($gregorian);

        self::assertSame(
            [$jy, $jm, $jd],
            Jalali::fromGregorian((int) $d->format('Y'), (int) $d->format('n'), (int) $d->format('j')),
            "تبدیل {$gregorian} اشتباه است"
        );
    }

    #[DataProvider('dates')]
    public function test_jalali_to_gregorian_round_trip(string $gregorian, int $jy, int $jm, int $jd): void
    {
        [$gy, $gm, $gd] = Jalali::toGregorian($jy, $jm, $jd);

        self::assertSame(
            $gregorian,
            sprintf('%04d-%02d-%02d', $gy, $gm, $gd),
            "برگشت {$jy}/{$jm}/{$jd} اشتباه است"
        );
    }

    /**
     * هفتهٔ ایرانی از شنبه شروع می‌شود، نه از دوشنبه یا یکشنبه.
     * هر گزارش «هفتگی» و هر تقویم به این وابسته است.
     */
    public function test_iranian_week_starts_on_saturday(): void
    {
        $expected = [
            '2026-09-19' => 0, // شنبه — اول هفته
            '2026-09-20' => 1, // یک‌شنبه
            '2026-09-21' => 2, // دوشنبه
            '2026-09-23' => 4, // چهارشنبه
            '2026-09-24' => 5, // پنج‌شنبه
            '2026-09-25' => 6, // جمعه — آخر هفته
        ];

        foreach ($expected as $date => $weekday) {
            self::assertSame($weekday, Jalali::weekday(new DateTimeImmutable($date)), $date);
        }
    }

    /** آخر هفتهٔ ایران پنج‌شنبه و جمعه است — اوج کار آرایشگاه. */
    public function test_weekend_is_thursday_and_friday(): void
    {
        self::assertTrue(Jalali::isWeekend(new DateTimeImmutable('2026-09-24')), 'پنج‌شنبه');
        self::assertTrue(Jalali::isWeekend(new DateTimeImmutable('2026-09-25')), 'جمعه');
        self::assertFalse(Jalali::isWeekend(new DateTimeImmutable('2026-09-19')), 'شنبه نباید آخر هفته باشد');
        self::assertFalse(Jalali::isWeekend(new DateTimeImmutable('2026-09-23')), 'چهارشنبه');
    }

    /** اسفند در سال کبیسه ۳۰ روز دارد. */
    public function test_leap_year_esfand_has_thirty_days(): void
    {
        foreach ([1399, 1403, 1408, 1412] as $leap) {
            self::assertTrue(Jalali::isJalaliLeapYear($leap), "{$leap} باید کبیسه باشد");
            self::assertSame(30, Jalali::daysInJalaliMonth($leap, 12), "اسفند {$leap}");
        }

        foreach ([1400, 1401, 1402, 1404, 1405] as $normal) {
            self::assertFalse(Jalali::isJalaliLeapYear($normal), "{$normal} نباید کبیسه باشد");
            self::assertSame(29, Jalali::daysInJalaliMonth($normal, 12), "اسفند {$normal}");
        }
    }

    /** شش ماه اول ۳۱ روز، شش ماه دوم ۳۰ روز. */
    public function test_month_lengths(): void
    {
        foreach (range(1, 6) as $m) {
            self::assertSame(31, Jalali::daysInJalaliMonth(1405, $m), "ماه {$m}");
        }
        foreach (range(7, 11) as $m) {
            self::assertSame(30, Jalali::daysInJalaliMonth(1405, $m), "ماه {$m}");
        }
    }

    public function test_persian_digits_round_trip(): void
    {
        self::assertSame('۱۴۰۵/۰۶/۲۹', Jalali::toPersianDigits('1405/06/29'));
        self::assertSame('1405/06/29', Jalali::fromPersianDigits('۱۴۰۵/۰۶/۲۹'));
        // ورودی مخلوط — کاربر با کیبورد فارسی نیمه‌کاره تایپ می‌کند
        self::assertSame('09123456789', Jalali::fromPersianDigits('۰۹۱۲۳۴۵۶۷۸۹'));
    }
