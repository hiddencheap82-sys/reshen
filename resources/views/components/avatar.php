<?php
/**
 * حرف اول نام، در یک مربع رنگی.
 *
 * چرا رنگ از خودِ نام درمی‌آید و نه تصادفی: باید هر بار همان رنگ
 * باشد. اگر «مهدی احمدی» امروز آبی و فردا سبز باشد، چشم دیگر از آن
 * برای پیدا کردنش کمک نمی‌گیرد و رنگ فقط سر و صدا می‌شود.
 *
 * چرا از پالت لهجه نمی‌آید: صاحب سالن پالت را عوض می‌کند و آن‌وقت
 * همهٔ آواتارها یک‌رنگ می‌شوند — یعنی همان حالتی که می‌خواستیم از آن
 * فرار کنیم.
 *
 * @var string      $name
 * @var string|null $avatarColor رنگ مشخص (مثلاً رنگ آرایشگر)، وگرنه از نام
 * @var string      $avatarSize  کلاس اندازه
 */
$avatarName = trim((string) ($name ?? ''));
$avatarLetter = $avatarName === '' ? '؟' : mb_substr($avatarName, 0, 1, 'UTF-8');
$avatarSize = $avatarSize ?? 'w-10 h-10 text-[13px]';

if (!empty($avatarColor)) {
    $avatarBg = $avatarColor;
} else {
    /*
     * دوازده فام، هر ۳۰ درجه یکی، همه با متن سفید بالای WCAG AA
     * (کم‌ترین ۴٫۷۰).
     *
     * چرا دوازده و نه شش: با شش رنگ، در فهرستی از هشت مشتری پنج‌تا
     * یک‌رنگ درمی‌آمدند. این ایرادِ hash نیست — با شش خانه، برخورد
     * همین‌قدر محتمل است. راهش زیاد کردن خانه‌هاست، نه عوض کردن hash؛
     * با دوازده رنگ، بیش از دو تکرار در یک صفحه نادر می‌شود.
     *
     * crc32 پایدار است — برخلاف hash تصادفی‌شدهٔ PHP که در هر اجرا
     * عوض می‌شود و همان آواتار را با هر بار باز کردن صفحه، رنگ دیگری
     * می‌داد.
     */
    $avatarPalette = [
        '#9F3838', '#9B6936', '#757529', '#547D2C', '#2E842E', '#2D8057',
        '#2C7D7D', '#386B9F', '#38389F', '#6B389F', '#9F389F', '#9F386B',
    ];
    /*
     * بیت‌های بالای crc32، نه پایینش.
     *
     * بیت‌های کم‌ارزشِ CRC32 برای ورودی‌های کوتاهِ هم‌شکل بد پخش
     * می‌شوند و ‎% 12‎ همان‌ها را می‌خواند: از هشت نامِ فهرستِ نمونه فقط
     * پنج رنگ درمی‌آمد. با شیفت ۱۶ بیتی همان هشت نام هفت رنگ می‌گیرند.
     */
    $avatarBg = $avatarPalette[(crc32($avatarName) >> 16) % count($avatarPalette)];
}
?>
<span class="<?= e($avatarSize) ?> shrink-0 rounded-xl grid place-items-center
             font-extrabold text-white select-none"
      style="background:<?= e($avatarBg) ?>" aria-hidden="true"><?= e($avatarLetter) ?></span>
