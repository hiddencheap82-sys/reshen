-- رنگ آرایشگرها را به پالتِ خوانا می‌برد.
--
-- حرف اول نام آرایشگر با متن سفید روی همین رنگ می‌نشیند. رنگ‌های
-- پیش‌فرضِ قبلی از ۴٫۵:۱ رد نمی‌شدند — #059669 نسبتش ۳٫۱۹ بود و
-- #d97706 نسبتش ۳٫۷۷ — یعنی روی صفحهٔ موبایل در نور روز خوانده
-- نمی‌شدند.
--
-- انتخابگر رنگ حالا فقط هشت رنگِ سنجیده‌شده را پیشنهاد می‌دهد، ولی
-- ردیف‌های قبلی همان مقدار قدیمی را دارند و کسی سراغشان نمی‌رود.
-- نگاشت به نزدیک‌ترین رنگِ هم‌خانواده است تا آرایشگری که «سبز» بوده
-- سبز بماند.

UPDATE staff SET color = CASE LOWER(color)
    WHEN '#2563eb' THEN '#1D4ED8'  -- آبی
    WHEN '#3b82f6' THEN '#1D4ED8'
    WHEN '#059669' THEN '#0F766E'  -- سبزآبی
    WHEN '#10b981' THEN '#0F766E'
    WHEN '#16a34a' THEN '#15803D'  -- سبز
    WHEN '#22c55e' THEN '#15803D'
    WHEN '#d97706' THEN '#C2410C'  -- نارنجی
    WHEN '#f59e0b' THEN '#C2410C'
    WHEN '#ea580c' THEN '#C2410C'
    WHEN '#dc2626' THEN '#B91C1C'  -- آجری
    WHEN '#ef4444' THEN '#B91C1C'
    WHEN '#e11d48' THEN '#9F1239'  -- زرشکی
    WHEN '#db2777' THEN '#9F1239'
    WHEN '#7c3aed' THEN '#6D28D9'  -- بنفش
    WHEN '#8b5cf6' THEN '#6D28D9'
    WHEN '#78716c' THEN '#44403C'  -- خاکستری
    WHEN '#6b7280' THEN '#44403C'
    ELSE color
  END
WHERE LOWER(color) NOT IN (
    '#1d4ed8','#0f766e','#15803d','#c2410c','#b91c1c','#9f1239','#6d28d9','#44403c'
);

-- هر چه از نگاشت بالا جا ماند (رنگ دستیِ ناشناخته) به آبی می‌رود؛
-- بهتر از ماندن روی رنگی است که متنش خوانده نمی‌شود.
UPDATE staff SET color = '#1D4ED8'
WHERE LOWER(color) NOT IN (
    '#1d4ed8','#0f766e','#15803d','#c2410c','#b91c1c','#9f1239','#6d28d9','#44403c'
);
