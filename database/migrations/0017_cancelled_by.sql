-- چه کسی نوبت را لغو کرد.
--
-- تا حالا فقط «لغو شد» را می‌دانستیم و دلیلش را. ولی «مشتری خودش لغو
-- کرد» و «آرایشگاه لغو کرد» دو چیز کاملاً متفاوت‌اند:
--
--   • اگر آرایشگاه زیاد لغو کند، مشتری‌ها می‌روند — و صاحب سالن باید
--     این را در گزارش ببیند، نه اینکه همه‌ی لغوها را پای مشتری بنویسد.
--   • نرخ غیبت و لغوِ مشتری، ورودیِ تصمیم «بیعانه بگیریم یا نه» است.
--
-- بدون این ستون، هر دو در یک عدد قاطی می‌شدند.

ALTER TABLE appointments
    ADD COLUMN cancelled_by ENUM('customer','salon','system') NULL DEFAULT NULL
        COMMENT 'کدام طرف لغو کرد' AFTER cancel_reason;

-- ردیف‌های قبلی: چیزی که با کد پیگیری لغو شده بود کار مشتری بود،
-- بقیه از پنل. تشخیصش از روی داده ممکن نیست، پس تهی می‌مانند —
-- بهتر از حدس زدن است.
