-- «هنوز ندیده» از این به بعد یعنی «از روزِ عضویت».
--
-- NewBookings پیش‌تر برای کاربری که هیچ‌وقت «رزروها» را باز نکرده بود
-- صفر برمی‌گرداند. نتیجه: صاحبِ سالنِ تازه اولین رزروهای اینترنتی‌اش
-- را هیچ‌جا نمی‌دید. حالا مبنا `salon_user.created_at` است.
--
-- ولی عضوهایی که *پیش از* این مهاجرت بوده‌اند و هنوز صفحه را باز
-- نکرده‌اند، با آن مبنا ناگهان همهٔ رزروهای آینده را «تازه» می‌دیدند
-- — همان نشانِ بی‌معنای «۴۷ نوبت تازه». پس برای آن‌ها، لحظهٔ ارتقا
-- مبنا می‌شود. روی نصبِ تازه جدول خالی است و این دستور کاری نمی‌کند.

UPDATE `salon_user`
   SET `bookings_seen_at` = CURRENT_TIMESTAMP
 WHERE `bookings_seen_at` IS NULL;
