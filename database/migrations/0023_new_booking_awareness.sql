-- آرایشگر باید بفهمد نوبت تازه آمده.
--
-- مشکلی که بی‌صدا بود: مشتری از اینترنت برای سه‌شنبهٔ بعد نوبت
-- می‌گرفت، پیامک تأییدش را هم می‌گرفت، و سالن هیچ خبری نداشت. صفحهٔ
-- «صف زنده» فقط امروز را نشان می‌دهد، پس نوبتِ هفتهٔ بعد تا وقتی کسی
-- خودش به «رزروها» سر نمی‌زد دیده نمی‌شد.
--
-- برای کسب‌وکاری که تازه از دفترچه به این سیستم آمده، این یعنی
-- بی‌اعتمادی: «معلوم نیست چیزی ثبت شده یا نه». و برای مشتری یعنی
-- رسیدن به سالنی که منتظرش نبوده.
--
-- دو ستون، دو راه‌حلِ مکمل:
--
-- ۱. `appointments.salon_notified_at` — پیامکِ «نوبت تازه» به شمارهٔ
--    سالن. کار می‌کند حتی وقتی پنل بسته است، که همان حالتِ شایع است.
--    ستون لازم است تا یک نوبت دو بار پیامک نگیرد؛ بدون آن، هر اجرای
--    دوباره یعنی پول اضافه و پیامک تکراری.
--
-- ۲. `salon_user.bookings_seen_at` — نشانِ «تازه» روی تب رزروها. هر
--    کاربر نشانِ خودش را دارد: صاحب سالن ممکن است دیده باشد و
--    پذیرش نه.

ALTER TABLE `appointments`
  ADD COLUMN `salon_notified_at` timestamp NULL DEFAULT NULL AFTER `created_ip`;

ALTER TABLE `salon_user`
  ADD COLUMN `bookings_seen_at` timestamp NULL DEFAULT NULL AFTER `is_active`;
