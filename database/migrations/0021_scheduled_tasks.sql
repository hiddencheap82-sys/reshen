-- زمان‌بندِ درخواست‌محور، به‌جای کرون.
--
-- چرا کرون حذف شد:
--
-- ۱. **راه‌اندازی‌اش بار اضافه بود.** صاحب آرایشگاه باید در cPanel
--    یک Cron Job می‌ساخت و دستور curl را درست تایپ می‌کرد. روی بعضی
--    هاست‌ها هم اصلاً `php` در دسترس نبود.
--
-- ۲. **نبودنش بی‌صدا بود.** اگر تنظیمش نمی‌کرد، هیچ‌چیز خطا نمی‌داد؛
--    فقط یادآورها نمی‌رفتند. راهنما خودش نوشته بود «این را رد نکنید»
--    که نشانهٔ یک طراحیِ شکننده است، نه یک هشدار خوب.
--
-- حالا هر درخواست وب، *بعد از اینکه پاسخ کاربر رفت*، نگاه می‌کند
-- کاری سررسید شده یا نه. پنل صف خودش هر ۱۵ ثانیه صفحه را تازه
-- می‌کند، پس در ساعت کاری ضربانِ مطمئنی وجود دارد.
--
-- بهایش را صریح می‌نویسم: **اگر هیچ‌کس سایت را باز نکند، هیچ کاری
-- اجرا نمی‌شود.** برای این محصول قابل قبول است چون کارهای زمان‌بندی
-- همه دربارهٔ روزی هستند که سالن باز است و پنلش باز است — ولی
-- یادآورِ ۲۴ ساعته در روزِ تعطیلِ سالن ممکن است دیر برود. به همین
-- دلیل خودِ یادآور هم «سررسیدی» شد، نه «پنجره‌ای»: اجرای دیر، هنوز
-- ارسال می‌کند.

CREATE TABLE IF NOT EXISTS `scheduled_tasks` (
  `name` varchar(60) NOT NULL,
  `last_run_at` timestamp NULL DEFAULT NULL,
  `last_result` varchar(255) DEFAULT NULL,
  `last_error` varchar(255) DEFAULT NULL,
  -- قفل، تا دو درخواست هم‌زمان یک کار را دو بار اجرا نکنند.
  -- زمان‌دار است نه بولی: اگر پروسه وسط کار بمیرد، قفل خودش باز
  -- می‌شود و کار برای همیشه گیر نمی‌کند.
  `locked_until` timestamp NULL DEFAULT NULL,
  `run_count` int(10) unsigned NOT NULL DEFAULT 0,
  PRIMARY KEY (`name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
