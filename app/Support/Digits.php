<?php

declare(strict_types=1);

namespace App\Support;

/**
 * ارقامی که کاربر ایرانی تایپ می‌کند.
 *
 * چرا این کلاس هست: صفحه‌کلیدِ فارسیِ گوشی، ارقام فارسی می‌نویسد
 * (۲۰۰۰۰۰)، و بعضی صفحه‌کلیدها عربی (٢٠٠٠٠٠). دو جا این ارقام بی‌صدا
 * صفر می‌شدند:
 *
 *   ۱. مرورگر: `<input type="number">` ارقام فارسی را قبول نمی‌کند،
 *      خطایی هم نشان نمی‌دهد — فیلد فقط خالی ارسال می‌شود.
 *   ۲. سرور: در PHP، ‎(int) "۲۰۰۰۰۰"‎ صفر است.
 *
 * نتیجه در عمل: آرایشگری که مبلغ را با صفحه‌کلید فارسی می‌زد، هر
 * پرداخت را «۰ تومان» ثبت می‌کرد و گزارش فروش بی‌صدا غلط می‌شد. قیمتِ
 * خدمت هم همین‌طور.
 *
 * فقط برای فیلدهای عددی است. متنِ آزاد (نام، یادداشت، پیام پشتیبانی)
 * نباید دست بخورد: «ساعت ۵ میام» باید همان‌طور بماند.
 */
final class Digits
{
    private const MAP = [
        '۰' => '0', '۱' => '1', '۲' => '2', '۳' => '3', '۴' => '4',
        '۵' => '5', '۶' => '6', '۷' => '7', '۸' => '8', '۹' => '9',
        '٠' => '0', '١' => '1', '٢' => '2', '٣' => '3', '٤' => '4',
        '٥' => '5', '٦' => '6', '٧' => '7', '٨' => '8', '٩' => '9',
        // ممیز فارسی و عربی
        '٫' => '.',
    ];

    /** ارقام فارسی و عربی ← لاتین. بقیهٔ نویسه‌ها دست نمی‌خورند. */
    public static function toLatin(string $value): string
    {
        return strtr($value, self::MAP);
    }

    /**
     * عدد صحیح از ورودیِ کاربر، یا null اگر عددی در آن نیست.
     *
     * جداکنندهٔ هزارگان (٬ و , و فاصله) پذیرفته می‌شود چون مردم
     * «۲۰۰٬۰۰۰» را همان‌طور می‌نویسند که روی صفحه می‌بینند.
     */
    public static function toInt(mixed $value): ?int
    {
        if ($value === null) {
            return null;
        }

        $clean = str_replace(['٬', ',', ' ', "\u{200C}", "\u{00A0}"], '', self::toLatin(trim((string) $value)));

        if ($clean === '' || preg_match('/^-?\d+$/', $clean) !== 1) {
            return null;
        }

        return (int) $clean;
    }

    /** مثل toInt، ولی با ممیز — برای درصد پورسانت. */
    public static function toFloat(mixed $value): ?float
    {
        if ($value === null) {
            return null;
        }

        $clean = str_replace(['٬', ',', ' ', "\u{200C}", "\u{00A0}"], '', self::toLatin(trim((string) $value)));

        if ($clean === '' || preg_match('/^-?\d+(\.\d+)?$/', $clean) !== 1) {
            return null;
        }

        return (float) $clean;
    }
}
