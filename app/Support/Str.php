<?php

declare(strict_types=1);

namespace App\Support;

final class Str
{
    private const TOKEN_ALPHABET = 'abcdefghjkmnpqrstuvwxyz23456789';

    /**
     * توکن کوتاه و غیرقابل‌حدس برای لینک‌های عمومی — مثل «x7k2m9pf».
     *
     * الفبا عمداً حرف‌های اشتباه‌گرفتنی ندارد (بدون i و l و o و صفر و
     * یک): این رشته گاهی از روی صفحه برای کسی خوانده می‌شود.
     */
    public static function token(int $length = 12): string
    {
        $alphabet = self::TOKEN_ALPHABET;
        $max = strlen($alphabet) - 1;
        $token = '';
        for ($i = 0; $i < $length; $i++) {
            $token .= $alphabet[random_int(0, $max)];
        }

        return $token;
    }

    /**
     * حرف‌نویسی فارسی به لاتین — برای ساختن slug.
     *
     * ترتیب مهم است: «خ» باید پیش از «ه» جایگزین شود وگرنه چیزی
     * نمی‌ماند. PHP آرایه را به ترتیب تعریف می‌پیماید، پس دوحرفی‌ها
     * بالا آمده‌اند.
     *
     * @var array<string,string>
     */
    private const TRANSLITERATION = [
        // دوحرفی‌ها اول
        'خ' => 'kh', 'چ' => 'ch', 'ش' => 'sh', 'ژ' => 'zh', 'غ' => 'gh', 'ق' => 'gh',
        // یک‌حرفی‌ها
        'آ' => 'a', 'ا' => 'a', 'أ' => 'a', 'إ' => 'e', 'ب' => 'b', 'پ' => 'p',
        'ت' => 't', 'ث' => 's', 'ج' => 'j', 'ح' => 'h', 'د' => 'd', 'ذ' => 'z',
        'ر' => 'r', 'ز' => 'z', 'س' => 's', 'ص' => 's', 'ض' => 'z', 'ط' => 't',
        'ظ' => 'z', 'ع' => 'a', 'ف' => 'f', 'ک' => 'k', 'ك' => 'k', 'گ' => 'g',
        'ل' => 'l', 'م' => 'm', 'ن' => 'n', 'ؤ' => 'o', 'ه' => 'h',
        'ة' => 'h', 'ي' => 'i', 'ئ' => 'i', 'ى' => 'a',
        // اعراب و نویسه‌های نامرئی
        'ء' => '', 'ّ' => '', 'َ' => 'a', 'ِ' => 'e', 'ُ' => 'o', 'ْ' => '',
        'ً' => 'an', 'ٍ' => 'en', 'ٌ' => 'on', 'ٔ' => '',
        "\u{200c}" => '-', "\u{200f}" => '', "\u{200e}" => '',
        // ارقام فارسی و عربی
        '۰' => '0', '۱' => '1', '۲' => '2', '۳' => '3', '۴' => '4',
        '۵' => '5', '۶' => '6', '۷' => '7', '۸' => '8', '۹' => '9',
        '٠' => '0', '١' => '1', '٢' => '2', '٣' => '3', '٤' => '4',
        '٥' => '5', '٦' => '6', '٧' => '7', '٨' => '8', '٩' => '9',
    ];

    /**
     * «و» و «ی» بسته به جایگاهشان صدای متفاوتی دارند.
     *
     * در اول کلمه صامت‌اند (ولی‌عصر → valiasr، یاسر → yaser) و در وسط
     * کلمه مصوت (کوروش → kurush، پیرایش → pirayesh). بدون این تفکیک
     * هر دو حالت یک حرف می‌گرفتند و نتیجه خواندنی نبود: «کوروش» به
     * kvrvsh تبدیل می‌شد.
     *
     * این قاعده کامل نیست — فارسی مصوت کوتاه نمی‌نویسد و هیچ جدولی
     * نمی‌تواند «سالن» را salon دربیاورد. برای همین صاحب سالن می‌تواند
     * نشانی عمومی را در تنظیمات دستی عوض کند؛ این فقط یک پیشنهاد
     * اولیهٔ آبرومند است.
     */
    private static function romanizeSemivowels(string $value): string
    {
        // اول کلمه: ابتدای رشته یا بعد از هر چیزی که حرف فارسی نیست.
        $value = preg_replace('/(^|[^\p{Arabic}])و/u', '$1v', $value) ?? $value;
        $value = preg_replace('/(^|[^\p{Arabic}])ی/u', '$1y', $value) ?? $value;

        // باقی‌مانده‌ها وسط کلمه‌اند.
        return strtr($value, ['و' => 'u', 'ی' => 'i']);
    }

    /**
     * نشانیِ خواندنی از یک نام.
     *
     * خروجی عمداً فقط ASCII است. اگر نام فارسی را همان‌طور نگه داریم،
     * لینک عمومی سالن پس از درصدرمزگذاری چیزی حدود ۱۰۰ کاراکتر می‌شود:
     *
     *   https://example.ir/s/%D8%A2%D8%B1%D8%A7%DB%8C%D8%B4%DA%AF%D8%A7%D9%87
     *
     * که نه در واتساپ خوب دیده می‌شود، نه دستی تایپ‌شدنی است، و QR را
     * هم بی‌دلیل متراکم می‌کند — همان QR که قرار است روی برگهٔ پشت
     * آینه چاپ شود و با دوربین موبایل خوانده شود.
     *
     * اگر از نام هیچ حرف لاتینی درنیاید (مثلاً نامی که فقط ایموجی
     * است)، رشتهٔ خالی برمی‌گردد و تصمیم با صداکننده است.
     */
    public static function slug(string $value): string
    {
        $value = mb_strtolower(trim($value));
        $value = self::romanizeSemivowels($value);
        $value = strtr($value, self::TRANSLITERATION);

        // هر چیزی که هنوز ASCII نیست — حروف لاتین‌دار مثل é، یا خطی که
        // در جدول بالا نیامده — به جداکننده تبدیل می‌شود.
        $value = preg_replace('/[^a-z0-9]+/u', '-', $value) ?? '';

        return trim($value, '-');
    }

    public static function otp(int $digits = 5): string
    {
        $max = (int) str_repeat('9', $digits);
        $min = (int) ('1' . str_repeat('0', $digits - 1));

        return (string) random_int($min, $max);
    }
}
